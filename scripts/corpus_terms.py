#!/usr/bin/env python3
"""Write corpus/terms.json: capitalised short words the corpus transcripts use (AEC, EDV, EPYC, ...).

agent/session.py treats a capitalised 2-5 letter word in a question as a ticker outside the corpus,
unless it is a corpus ticker, a common abbreviation, or one of these terms. Without this list, a
question about a product ("How is EPYC doing?") would be answered "I don't have calls for EPYC".

    python scripts/corpus_terms.py     # reads corpus/v2/raw, offline

It also writes proper_nouns: capitalised words the transcripts use and the speakers' names, lowercased
(lisa, instinct, venice, europe...). session.unrecognised_company never takes them for a company, so
"What did Lisa Su say?" after an AMD question stays on AMD.

The output is a word list, no transcript text, so it is committed. Rerun after changing the corpus.
Known cost: a real ticker spoken on a call (ARM, HPE) is on the list and is not flagged as outside the corpus.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "agent"))

import session  # noqa: E402

RAW = ROOT / "corpus" / "v2" / "raw"
OUT = ROOT / "corpus" / "terms.json"


def terms(raw: Path = RAW) -> list[str]:
    corpus = session.Corpus.load()
    corpus.terms = set()  # the list being built must not filter itself
    found: set[str] = set()
    for f in sorted(raw.glob("*.json")):
        for turn in json.loads(f.read_text())["data"]:
            found.update(session.unknown_tickers(turn.get("text") or "", corpus))
    return sorted(found)


def proper_nouns(raw: Path = RAW) -> list[str]:
    found: set[str] = set()
    for f in sorted(raw.glob("*.json")):
        for turn in json.loads(f.read_text())["data"]:
            found.update(w.lower() for w in re.findall(r"(?<![\w&.-])[A-Z][a-z][\w&-]*", turn.get("text") or ""))
            found.update(w.lower() for w in re.findall(r"[A-Za-z][\w&-]+", turn.get("speakerName") or ""))
    return sorted(found)


def main() -> int:
    words = terms()
    if not words:
        sys.exit(f"no transcripts in {RAW}")
    nouns = proper_nouns()
    comment = ("Capitalised short words the corpus transcripts use (terms), and capitalised words and speaker names "
               "they use, lowercased (proper_nouns). agent/session.py never takes a term for a ticker outside the "
               "corpus, or a proper noun for an unknown company. Generated by scripts/corpus_terms.py; rerun after "
               "changing the corpus.")
    OUT.write_text(json.dumps({"_comment": comment, "terms": words, "proper_nouns": nouns}, indent=0) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(words)} terms, {len(nouns)} proper nouns")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
